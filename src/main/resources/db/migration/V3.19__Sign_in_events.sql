-- 2.17.1: the history of signing in and out - every authentication decision, as OWASP's logging guidance and ASVS
-- (V7: "all authentication decisions are logged") ask, and what an ISO 27001 review reads (A.8.15).
--
-- One row per event, written off the request by SignInRecorder, never in the request's transaction:
--
--   SIGNED_IN        a person signed in on the form (a session begins)
--   SIGN_IN_FAILED   a sign-in refused - on the form (channel WEB) or by the v1 API's password (channel API);
--                    reason BAD_CREDENTIALS, LOCKED (refused while the name is locked), LOCKED_NOW (this failure
--                    locked it), DISABLED, UNAVAILABLE (the directory did not answer) or OTHER
--   SIGNED_OUT       a person signed out
--   SESSION_ENDED    a session ended by an administrator, or with its account disabled
--   SESSION_EXPIRED  a session that timed out, idle
--
-- Not recorded: a successful request of the v1 API's password or of an API key - every call is one, and the
-- download and action records already say what they did. Never stored: a password, or a session's id (the cookie
-- that signs its holder in); a session is named by ActiveUserSessions.handleOf, a digest, so its sign-in and its
-- end can be read together.
--
--   username     as typed - for a failure, whatever was typed, which may name no account
--   user_id      the account of that name when the row was written, or NULL; set to NULL if the account goes
--   address      the client's, behind the proxy as the download records take it
--   user_agent   the browser, cut to 300 characters
--
-- Kept filemanagement.sign-ins.retention-days (365) and removed every night, a batch at a time.

CREATE TABLE sign_in_event (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at     timestamptz(3) NOT NULL,
    event           varchar(20)    NOT NULL,
    channel         varchar(10)    NOT NULL,
    username        varchar(150),
    user_id         integer,
    address         varchar(45),
    user_agent      varchar(300),
    reason          varchar(20),
    session_handle  varchar(64),
    CONSTRAINT fk_sign_in_event_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_sign_in_event_event CHECK (event IN ('SIGNED_IN', 'SIGN_IN_FAILED', 'SIGNED_OUT', 'SESSION_ENDED',
                                                       'SESSION_EXPIRED')),
    CONSTRAINT ck_sign_in_event_channel CHECK (channel IN ('WEB', 'API'))
);

-- The page: newest first, a page at a time; one person's; one name as typed (a failure names no account).
CREATE INDEX ix_sign_in_event_time ON sign_in_event (occurred_at DESC, id DESC);
CREATE INDEX ix_sign_in_event_user ON sign_in_event (user_id, occurred_at DESC) WHERE user_id IS NOT NULL;
CREATE INDEX ix_sign_in_event_username ON sign_in_event (upper(username) varchar_pattern_ops, occurred_at DESC);
