-- Roadmap Phase 14 (2.17.0): folder classes - a type on each folder, and access granted by type.
--
-- Nothing here gives any folder a class: every folder's class_id is NULL and its class_path '/', so every
-- folder, every grant and every upload behaves exactly as before until somebody defines a class and sets it.
--
--   folder_class        a class: its name (unique without case) and title, and three settings that are the
--                       class's, never a folder's -
--                         container_only           files refused directly in a folder of it
--                         other_children           a subfolder whose name its template does not hold is made
--                                                  NONE (without a class), CLASS (with other_children_class_id)
--                                                  or REFUSE (not made)
--   folder_class_child  its template: the folders made in a folder of the class as soon as it is made, each
--                       with its label and class, in position order; names unique per class without case
--   folder.class_id     the folder's class, or NULL
--   folder.class_path   derived, like key_path: the classes of the folders above and of this one, each
--                       followed by '/', after a leading '/' - '/' for none, '/3/9/' for 3 above 9. What the
--                       access test reads: a class grant covers a folder whose class_path holds '/<class>/'
--   role_class_grant    a role's grant on a class - READ or WRITE - within a scope folder, or everywhere
--                       (scope_folder_id NULL): one row whatever the number of folders of the class.

CREATE TABLE folder_class (
    id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                     varchar(100)   NOT NULL,
    title                    varchar(200)   NOT NULL,
    container_only           boolean        NOT NULL DEFAULT FALSE,
    other_children           varchar(10)    NOT NULL DEFAULT 'NONE',
    other_children_class_id  integer,
    created_at               timestamptz(0) NOT NULL,
    created_by               integer,
    updated_at               timestamptz(0),
    updated_by               integer,
    CONSTRAINT fk_folder_class_other_class FOREIGN KEY (other_children_class_id) REFERENCES folder_class (id),
    CONSTRAINT fk_folder_class_created_by FOREIGN KEY (created_by) REFERENCES app_user (id),
    CONSTRAINT fk_folder_class_updated_by FOREIGN KEY (updated_by) REFERENCES app_user (id),
    CONSTRAINT ck_folder_class_other_children CHECK (other_children IN ('NONE', 'CLASS', 'REFUSE')),
    CONSTRAINT ck_folder_class_other_class CHECK ((other_children = 'CLASS') = (other_children_class_id IS NOT NULL))
);

CREATE UNIQUE INDEX uq_folder_class_name ON folder_class (upper(name));
CREATE INDEX ix_folder_class_other_class ON folder_class (other_children_class_id) WHERE other_children_class_id IS NOT NULL;
CREATE INDEX ix_folder_class_created_by ON folder_class (created_by);
CREATE INDEX ix_folder_class_updated_by ON folder_class (updated_by);

CREATE TABLE folder_class_child (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id        integer        NOT NULL,
    name            varchar(100)   NOT NULL,
    display_name    varchar(200)   NOT NULL,
    child_class_id  integer        NOT NULL,
    position        integer        NOT NULL,
    CONSTRAINT fk_folder_class_child_class FOREIGN KEY (class_id) REFERENCES folder_class (id) ON DELETE CASCADE,
    CONSTRAINT fk_folder_class_child_child_class FOREIGN KEY (child_class_id) REFERENCES folder_class (id)
);

CREATE UNIQUE INDEX uq_folder_class_child_name ON folder_class_child (class_id, upper(name));
CREATE INDEX ix_folder_class_child_child_class ON folder_class_child (child_class_id);

ALTER TABLE folder ADD COLUMN class_id integer;
ALTER TABLE folder ADD COLUMN class_path varchar(1000) NOT NULL DEFAULT '/';
ALTER TABLE folder ADD CONSTRAINT fk_folder_class FOREIGN KEY (class_id) REFERENCES folder_class (id);
-- The folders of a class, under a path: what a class grant covers, and the folders on the way to them.
CREATE INDEX ix_folder_class_path ON folder (class_id, path varchar_pattern_ops) WHERE class_id IS NOT NULL;

CREATE TABLE role_class_grant (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id          integer      NOT NULL,
    class_id         integer      NOT NULL,
    permission       varchar(10)  NOT NULL,
    scope_folder_id  integer,
    CONSTRAINT fk_role_class_grant_role FOREIGN KEY (role_id) REFERENCES role (id) ON DELETE CASCADE,
    CONSTRAINT fk_role_class_grant_class FOREIGN KEY (class_id) REFERENCES folder_class (id),
    CONSTRAINT fk_role_class_grant_scope FOREIGN KEY (scope_folder_id) REFERENCES folder (id) ON DELETE CASCADE,
    CONSTRAINT ck_role_class_grant_permission CHECK (permission IN ('READ', 'WRITE'))
);

CREATE UNIQUE INDEX uq_role_class_grant ON role_class_grant (role_id, class_id, COALESCE(scope_folder_id, 0));
CREATE INDEX ix_role_class_grant_class ON role_class_grant (class_id);
CREATE INDEX ix_role_class_grant_scope ON role_class_grant (scope_folder_id) WHERE scope_folder_id IS NOT NULL;
