-- 2.19.0: webhooks (roadmap 13.18) - what S3 calls event notifications: a subscription on a folder (with everything
-- beneath it, or itself alone) or on a folder class, and every time a file there is uploaded, given a version, deleted,
-- restored, purged, moved or described, a JSON POSTed to an address - n8n, the ERP - which knows at once.
--
-- Born where every change to a file is recorded: FileHistoryService.record, in the transaction of the change. A row
-- of webhook_delivery per subscription the event matches is written there (an outbox): a change that rolls back sends
-- nothing, one that commits is delivered at least once, whatever dies between. A worker sends them off the request.
--
-- webhook
--   scope            SUBTREE - the folder and everything beneath it, at any depth; FOLDER - the folder alone;
--                    CLASS - every folder of the class and beneath one, within folder_id when it is set
--   folder_id        the folder (SUBTREE, FOLDER), or the class's limit (CLASS); NULL once that folder is purged -
--                    the subscription then matches nothing, and says so on its page
--   class_id         CLASS: the class; NULL once it is deleted, likewise
--   events           the events sent, comma-separated (WebhookEvent)
--   extensions       the files' extensions sent, comma-separated, lower case; empty for any
--   name_pattern     a glob on the file's name with its extension (* and ?), without case; empty for any
--   actors           ALL, PEOPLE (no key acted) or KEYS (an API key acted)
--   excluded_key_ids the API keys whose events are never sent, comma-separated - n8n's own, so that what it uploads
--                    in reply to an event is not an event to it again
--   signing_secret   the secret every request is signed with (HMAC-SHA256), encrypted as an S3 key's secret is
--                    (AES-256-GCM, the master key); previous_* the one replaced, still signed with for an hour
--   auth_*           what the receiver asks of a caller: a header of its own (HEADER: auth_name, the value) or Basic
--                    (BASIC: auth_name the user, the password) - the value encrypted likewise
--   rate_per_minute, concurrency, pause_after   how fast it is sent to, and after how many failures in a row it is
--                    paused by itself (paused_reason AUTO), until someone resumes it
CREATE TABLE webhook (
    id                           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                         varchar(100)   NOT NULL,
    url                          varchar(2000)  NOT NULL,
    scope                        varchar(10)    NOT NULL,
    folder_id                    integer,
    class_id                     integer,
    events                       varchar(400)   NOT NULL,
    extensions                   varchar(300)   NOT NULL DEFAULT '',
    name_pattern                 varchar(200)   NOT NULL DEFAULT '',
    actors                       varchar(10)    NOT NULL DEFAULT 'ALL',
    excluded_key_ids             varchar(500)   NOT NULL DEFAULT '',
    signing_secret               varchar(300)   NOT NULL,
    previous_signing_secret      varchar(300),
    previous_secret_until        timestamptz(0),
    auth_kind                    varchar(10)    NOT NULL DEFAULT 'NONE',
    auth_name                    varchar(200),
    auth_secret                  varchar(1000),
    rate_per_minute              integer        NOT NULL,
    concurrency                  integer        NOT NULL,
    pause_after                  integer        NOT NULL,
    enabled                      boolean        NOT NULL DEFAULT true,
    paused_reason                varchar(10),
    paused_at                    timestamptz(0),
    consecutive_failures         integer        NOT NULL DEFAULT 0,
    created_at                   timestamptz(0) NOT NULL,
    created_by                   integer        NOT NULL,
    updated_at                   timestamptz(0),
    updated_by                   integer,
    CONSTRAINT ck_webhook_scope CHECK (scope IN ('SUBTREE', 'FOLDER', 'CLASS')),
    CONSTRAINT ck_webhook_actors CHECK (actors IN ('ALL', 'PEOPLE', 'KEYS')),
    CONSTRAINT ck_webhook_auth CHECK (auth_kind IN ('NONE', 'HEADER', 'BASIC')
        AND (auth_kind = 'NONE') = (auth_secret IS NULL)),
    CONSTRAINT ck_webhook_paused CHECK (paused_reason IS NULL OR paused_reason IN ('MANUAL', 'AUTO')),
    CONSTRAINT ck_webhook_limits CHECK (rate_per_minute BETWEEN 1 AND 6000 AND concurrency BETWEEN 1 AND 16
        AND pause_after BETWEEN 1 AND 10000),
    CONSTRAINT fk_webhook_folder FOREIGN KEY (folder_id) REFERENCES folder (id) ON DELETE SET NULL,
    CONSTRAINT fk_webhook_class FOREIGN KEY (class_id) REFERENCES folder_class (id) ON DELETE SET NULL,
    CONSTRAINT fk_webhook_created_by FOREIGN KEY (created_by) REFERENCES app_user (id),
    CONSTRAINT fk_webhook_updated_by FOREIGN KEY (updated_by) REFERENCES app_user (id)
);
CREATE UNIQUE INDEX uq_webhook_name ON webhook (upper(name));
CREATE INDEX ix_webhook_folder ON webhook (folder_id) WHERE folder_id IS NOT NULL;
CREATE INDEX ix_webhook_class ON webhook (class_id) WHERE class_id IS NOT NULL;
CREATE INDEX ix_webhook_created_by ON webhook (created_by);
CREATE INDEX ix_webhook_updated_by ON webhook (updated_by) WHERE updated_by IS NOT NULL;

-- One delivery: one event to one subscription.
--   event_id      the event's own (the same for every subscription it went to): X-FM-Event-Id, what a receiver
--                 drops a second copy by
--   event         the payload's eventName (s3:ObjectCreated:Put, fm:ObjectRestored, ...); TEST for a test event
--   payload       what is POSTed, as it was when the event happened
--   state         PENDING (to send, at next_attempt_at), SENDING (a worker holds it until lease_until),
--                 DELIVERED (a 2xx), FAILED (no more attempts; sent again only by hand)
--   last_status   the receiver's answer to the last attempt, or NULL for none (a timeout, a refused connection)
--   last_error    why the last attempt failed, cut short - never the payload
-- Finished deliveries are kept filemanagement.webhooks.retention-days and removed every night.
CREATE TABLE webhook_delivery (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    webhook_id        integer        NOT NULL,
    event_id          uuid           NOT NULL,
    event             varchar(40)    NOT NULL,
    file_info_id      integer,
    file_name         varchar(250),
    occurred_at       timestamptz(3) NOT NULL,
    payload           jsonb          NOT NULL,
    state             varchar(10)    NOT NULL,
    attempts          integer        NOT NULL DEFAULT 0,
    next_attempt_at   timestamptz(3) NOT NULL,
    lease_until       timestamptz(3),
    last_attempt_at   timestamptz(3),
    last_status       integer,
    last_error        varchar(500),
    delivered_at      timestamptz(3),
    CONSTRAINT ck_webhook_delivery_state CHECK (state IN ('PENDING', 'SENDING', 'DELIVERED', 'FAILED')),
    CONSTRAINT fk_webhook_delivery_webhook FOREIGN KEY (webhook_id) REFERENCES webhook (id) ON DELETE CASCADE
);
-- The worker: a subscription's due deliveries, oldest first; the leases a dead worker left.
CREATE INDEX ix_webhook_delivery_due ON webhook_delivery (webhook_id, next_attempt_at, id) WHERE state = 'PENDING';
CREATE INDEX ix_webhook_delivery_lease ON webhook_delivery (lease_until) WHERE state = 'SENDING';
-- The page: a subscription's deliveries, newest first, a page at a time; the nightly removal, oldest first.
CREATE INDEX ix_webhook_delivery_page ON webhook_delivery (webhook_id, occurred_at DESC, id DESC);
CREATE INDEX ix_webhook_delivery_finished ON webhook_delivery (occurred_at) WHERE state IN ('DELIVERED', 'FAILED');
