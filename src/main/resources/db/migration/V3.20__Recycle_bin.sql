-- 2.18.0: the recycle bin (roadmap 13.1). A delete - of a file, a revision, a folder or a folder with everything in
-- it, by any way - no longer removes anything: it moves what was deleted into the bin, where nothing finds it, and
-- records the deletion. It is restored from there, or purged: by hand, or every night once it is older than
-- filemanagement.trash.retention-days. Only a purge removes rows and bytes.
--
-- The bin is a folder of its own, OUTSIDE the tree: no parent, id 0, path /0/. Every grant is on a folder of the
-- tree under the root, so none covers it - not a grant on the root, not a class grant on every folder of a class -
-- and the grants on folders that are in it are left out of every grant (GrantedFolderPath). What has no grant to
-- read through, an administrator's queries leave out by its path (Bin.PATH). Its id is fixed so that its path is a
-- constant every statement can name; no folder has id 0 (identities begin at 1).
--
-- Each deletion is an entry, and has a folder of its own in the bin - its holder, named by a random UUID - so that
-- two deleted files, or folders, of one name never meet: the file, the folder (with everything beneath it) or, for
-- a revision deleted alone, a file made to hold it, sit in the holder. Nothing else is ever put in the bin.

INSERT INTO folder (id, parent_id, name, search_name, display_name, search_display_name, path, depth, kind,
                    enabled, state, created_at, key_path, class_path)
VALUES (0, NULL, 'Bin', 'BIN', 'Bin', 'BIN', '/0/', 0, 'TRASH', 1, 0, LOCALTIMESTAMP(0), '', '/');

-- kind          FILE - a file with every revision; REVISION - one revision, in a file made to hold it;
--               FOLDER - a folder with everything beneath it
-- holder_folder_id   the entry's folder in the bin
-- file_info_id       FILE: the file; REVISION: the file holding the revision
-- file_details_id    REVISION: the revision
-- folder_id          FOLDER: the folder
-- original_file_info_id   REVISION: the file it was a revision of - NULL once that file is purged
-- origin_folder_id   the folder it was in (a folder's parent) - NULL once that folder is purged
-- origin_path        that folder's path: as it is now while the folder is in the tree (a move of it, or of a
--                    folder above it, rewrites it), as it was when the folder itself went to the bin or was purged.
--                    Who may restore the entry is who may write there; the quotas above it count the entry's bytes
-- origin_title       where it was, as a person read it then (the folders' labels, as the history keeps them)
-- original_name      the name it had there (a file's, a revision's file's, a folder's)
-- search_name        SearchKey of original_name: what the bin page's search compares
-- deleted_by / deleted_by_api_key_id   who deleted it, and with which key when a key did
-- bytes, files, folders   what it holds: every revision's size, the files, the folders (a folder counts itself)
CREATE TABLE trash_entry (
    id                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                   varchar(10)    NOT NULL,
    holder_folder_id       integer        NOT NULL,
    file_info_id           integer,
    file_details_id        integer,
    folder_id              integer,
    original_file_info_id  integer,
    origin_folder_id       integer,
    origin_path            varchar(1000)  NOT NULL,
    origin_title           varchar(1000),
    original_name          varchar(100)   NOT NULL,
    search_name            varchar(200)   NOT NULL,
    deleted_at             timestamptz(0) NOT NULL,
    deleted_by             integer        NOT NULL,
    deleted_by_api_key_id  integer,
    bytes                  bigint         NOT NULL,
    files                  integer        NOT NULL,
    folders                integer        NOT NULL,
    CONSTRAINT ck_trash_entry_kind CHECK (kind IN ('FILE', 'REVISION', 'FOLDER')),
    CONSTRAINT ck_trash_entry_what CHECK (
        (kind = 'FILE' AND file_info_id IS NOT NULL AND file_details_id IS NULL AND folder_id IS NULL)
        OR (kind = 'REVISION' AND file_info_id IS NOT NULL AND file_details_id IS NOT NULL AND folder_id IS NULL)
        OR (kind = 'FOLDER' AND folder_id IS NOT NULL AND file_info_id IS NULL AND file_details_id IS NULL)),
    CONSTRAINT uq_trash_entry_holder UNIQUE (holder_folder_id),
    -- Checked at the commit: a restore or a purge removes the entry and what it names in one transaction, in
    -- whichever order its statements come - never one without the other.
    CONSTRAINT fk_trash_entry_holder FOREIGN KEY (holder_folder_id) REFERENCES folder (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_trash_entry_file FOREIGN KEY (file_info_id) REFERENCES file_info (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_trash_entry_revision FOREIGN KEY (file_details_id) REFERENCES file_details (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_trash_entry_folder FOREIGN KEY (folder_id) REFERENCES folder (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_trash_entry_original_file FOREIGN KEY (original_file_info_id) REFERENCES file_info (id)
        ON DELETE SET NULL,
    CONSTRAINT fk_trash_entry_origin FOREIGN KEY (origin_folder_id) REFERENCES folder (id) ON DELETE SET NULL,
    CONSTRAINT fk_trash_entry_deleted_by FOREIGN KEY (deleted_by) REFERENCES app_user (id),
    CONSTRAINT fk_trash_entry_api_key FOREIGN KEY (deleted_by_api_key_id) REFERENCES api_key (id)
);

-- The page: newest first, a page at a time (keyset); one person's deletions; and the nightly purge, oldest first.
CREATE INDEX ix_trash_entry_deleted_at ON trash_entry (deleted_at DESC, id DESC);
CREATE INDEX ix_trash_entry_deleted_by ON trash_entry (deleted_by, deleted_at DESC);
-- What was deleted from below a folder: the quotas, and who may restore (write access on the origin) - a range
-- of the index per granted path; and the entries of the folders a move rewrites.
CREATE INDEX ix_trash_entry_origin_path ON trash_entry (origin_path varchar_pattern_ops);
CREATE INDEX ix_trash_entry_origin ON trash_entry (origin_folder_id) WHERE origin_folder_id IS NOT NULL;
-- A revision's file: what the file page says is in the bin, and a revision restored to it.
CREATE INDEX ix_trash_entry_original_file ON trash_entry (original_file_info_id) WHERE original_file_info_id IS NOT NULL;
CREATE INDEX ix_trash_entry_search_name_trgm ON trash_entry USING gin (replace(search_name, ' ', '') gin_trgm_ops);
-- The foreign keys a purge deletes through.
CREATE INDEX ix_trash_entry_file ON trash_entry (file_info_id) WHERE file_info_id IS NOT NULL;
CREATE INDEX ix_trash_entry_revision ON trash_entry (file_details_id) WHERE file_details_id IS NOT NULL;
CREATE INDEX ix_trash_entry_folder ON trash_entry (folder_id) WHERE folder_id IS NOT NULL;
CREATE INDEX ix_trash_entry_api_key ON trash_entry (deleted_by_api_key_id) WHERE deleted_by_api_key_id IS NOT NULL;
